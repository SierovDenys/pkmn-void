#===============================================================================
# Extra Autotiles — анимированные автотайлы сверх лимита в 7 слотов.
#===============================================================================
# Механизм штатный, встроен в Essentials v21 (секция скрипта "TilemapRenderer",
# константа EXTRA_AUTOTILES). Здесь она только наполняется из плагина, чтобы не
# править основные скрипты.
#
# Формат: tileset_id => [[большие автотайлы], [одиночные автотайлы]]
#
#-------------------------------------------------------------------------------
# ЧТО ЗДЕСЬ И ПОЧЕМУ
#-------------------------------------------------------------------------------
# Большие автотайлы (dirt_water, dirt_water_tr, water, water_tr) живут в обычных
# 7 слотах тайлсета — им нужна автостыковка при рисовании, а её дают только
# настоящие слоты.
#
# Угловые кладутся руками, автостыковка им не нужна — нужна только анимация.
# Поэтому они идут сюда, во второй массив, и стоят 1 ID вместо 48.
#
#-------------------------------------------------------------------------------
# РАСКЛАДКА ID
#-------------------------------------------------------------------------------
# Больших автотайлов здесь НЕТ, поэтому одиночные начинаются сразу с ID 384:
#   single_autotile_start_id = 384 + (кол-во больших) * 48 = 384
#
# Порядок в массиве = порядок ID. Под них зарезервированы верхние 6 рядов
# Outside_0.png (ID 384..431, 48 мест); занято 16, свободно 32.
#
#   ряд 0, ID 384..391 — water (4 угла) + water_tr (4 угла)
#   ряд 1, ID 392..399 — dirt_water (4 угла) + dirt_water_tr (4 угла)
#
# НЕ добавлять сюда большие автотайлы: они считаются первыми, и появление хотя бы
# одного сдвинет все одиночные на 48 ID, сломав уже нарисованные карты.
# Дописывать одиночные можно только в КОНЕЦ массива.
#
#-------------------------------------------------------------------------------
# ПОСЛЕ ИЗМЕНЕНИЙ ЗДЕСЬ
#-------------------------------------------------------------------------------
# Passage, Priority и Terrain Tag берутся из тайлсета по исходному ID тайла, а не
# из автотайла (map.terrain_tags[tile_id]). Значит плейсхолдерам в верхних рядах
# надо выставить нужные проходимость и terrain tag в базе данных.
#
# Все файлы — 256x32, 8 кадров. Скорость по умолчанию 0.25 с на кадр
# (AUTOTILE_FRAME_DURATION = 5). Чтобы замедлить конкретный автотайл,
# переименуй файл в вида "water_top_left[10].png" (10/20 = 0.5 с) и поправь
# имя в списке ниже.
#===============================================================================

TilemapRenderer::EXTRA_AUTOTILES.merge!(
  # water_tr объявлен ОДИНОЧНЫМ автотайлом (второй массив) и занимает ОДИН ID —
  # 384, хотя файл у него полноценный 768x192, как у большого.
  #
  # Так можно потому, что номер варианта стыковки подставляет плагин
  # "Autotile Autoconnect", а не адресация ID. Штатный большой автотайл съел бы
  # 48 ID (весь резерв) ради того же результата.
  #
  # Рисовать одним тайлом 384, стыковку игра подставит сама. В редакторе RMXP
  # стыковки не видно — там всегда тот тайл, которым рисуешь.
  #
  # Свободно ID 385..431 — ещё 47 таких же автотайлов.
  1 => [[], ["water_tr"]]
)

#-------------------------------------------------------------------------------
# Прежние 16 одиночных углов убраны намеренно.
#
# После того как в основных автотайлах заполнена клетка (2,0) и добавлены два
# ряда expanded format, внутренние углы собираются штатно и с автостыковкой в
# редакторе. Отдельные угловые автотайлы стали не нужны, а их ID (384..399)
# всё равно пересекаются с блоком большого автотайла.
#-------------------------------------------------------------------------------
