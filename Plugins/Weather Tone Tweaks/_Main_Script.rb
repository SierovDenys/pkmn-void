#===============================================================================
# Weather Tone Tweaks — смягчение экранного тона погоды.
#===============================================================================
# ЗАЧЕМ
#
# Ясная погода (:Sun) в ядре задана так:
#
#   :tone_proc => proc { |strength| next Tone.new(64, 64, 32, 0) }
#
# Это +64 к красному и зелёному и +32 к синему — сильная тёплая засветка,
# из-за которой зелень уходит в жёлтый и картинка выглядит выцветшей.
# Параметр strength (0..60) там игнорируется, тон всегда максимальный.
#
# КАК ЭТО РАБОТАЕТ
#
# Tone.new(red, green, blue, gray):
#   red/green/blue — прибавка к каналу, от -255 до 255
#   gray           — обесцвечивание, от 0 до 255
#
# Тон применяется в RPG::Weather#update_screen_tone. Перерегистрация погоды
# перезаписывает запись целиком (GameData::Weather.register:
# DATA[hash[:id]] = DATA[hash[:id_number]] = self.new(hash)), а плагины грузятся
# после ядра — поэтому достаточно объявить погоду заново.
#
# ВАЖНО
#
# Свойства НЕ наследуются: register создаёт объект заново, и всё, что здесь не
# перечислено, станет nil/false. Поэтому :category обязательно дублируется —
# по категории работают способности, снижающие частоту встреч, и некоторые
# методы эволюции. У :Sun нет графики и смещений, так что остальных полей нет.
#
# ПОДБОР ЗНАЧЕНИЙ
#
#   Tone.new(64, 64, 32, 0)   исходный вариант ядра — очень ярко
#   Tone.new(32, 32, 16, 0)   половина — заметное солнце без засветки  <- по умолчанию
#   Tone.new(16, 16,  8, 0)   лёгкий тёплый оттенок, почти незаметно
#   Tone.new(24, 24, 12, 8)   мягче и чуть менее насыщенно (gray = 8)
#
# Пропорция 2:2:1 сохраняет исходный тёплый оттенок. Если поднять третье число
# ближе к первым двум, свет станет белым вместо желтоватого.
#===============================================================================

module WeatherToneTweaks
  SUN_TONE = Tone.new(32, 32, 16, 0)
end

GameData::Weather.register({
  :id        => :Sun,
  :id_number => 7,
  :category  => :Sun,
  :tone_proc => proc { |_strength| next WeatherToneTweaks::SUN_TONE.clone }
})
