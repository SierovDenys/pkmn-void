#===============================================================================
# Deep Grass — персонаж остаётся утопленным в траве и во время движения.
#===============================================================================
# ПРОБЛЕМА
#
# В Game_Character#calculate_bush_depth есть два режима:
#
#   if deepBush?(...)                      # глубокий куст
#     if moving?
#       @bush_depth = TILE_HEIGHT if <тайл сзади тоже глубокий>
#     else
#       @bush_depth = TILE_HEIGHT          # 32 px
#     end
#   elsif bush?(...) && !moving?           # обычный куст
#     @bush_depth = 12
#   end
#
# Обычный куст ГАСИТСЯ при движении явным условием `&& !moving?` — это
# унаследовано из ванильного RPG Maker, где bush задуман под низкие кустики
# и подрезает только ступни. Глубокий режим Essentials добавил уже под
# покемоновские заросли, и там эффект при ходьбе сохраняется.
#
# РЕШЕНИЕ
#
# Флаг :deep_bush есть только у :TallGrass (id_number 10), но редактор RMXP
# принимает Terrain Tag лишь 0..7, а все номера 0..7 заняты стандартными
# тегами. Ставить 10 пришлось бы через Debug menu -> "Edit terrain tags",
# и RMXP может сбросить такое значение в 0 при следующей правке тайлсета
# в Database.
#
# Поэтому проще добавить :deep_bush прямо к :Grass (тег 2). Повторная
# регистрация перезаписывает запись (GameData::TerrainTag.register:
# DATA[hash[:id]] = DATA[hash[:id_number]] = self.new(hash)), а плагины
# грузятся после ядра.
#
# ВАЖНО
#
# Свойства НЕ наследуются — register создаёт объект заново, и всё, что здесь
# не перечислено, станет false/nil. Поэтому ниже продублированы все исходные
# поля :Grass.
#
# Затрагиваются только тайлы, у которых есть И тег 2, И Bush Flag:
#   return true if terrain.deep_bush && @passages[tile_id] & 0x40 == 0x40
# Декоративная трава без Bush Flag не меняется никак.
#
# Сознательно НЕ копируем из :TallGrass:
#   :must_walk              — иначе в траве нельзя бежать и ездить на велосипеде
#   :double_wild_encounters — иначе удвоенная частота встреч и двойные бои
#===============================================================================

GameData::TerrainTag.register({
  :id                   => :Grass,
  :id_number            => 2,
  :shows_grass_rustle   => true,
  :land_wild_encounters => true,
  :battle_environment   => :Grass,
  :deep_bush            => true
})

#===============================================================================
# Глубина подрезки на тег.
#===============================================================================
# :deep_bush жёстко задаёт глубину Game_Map::TILE_HEIGHT = 32 px. Кадр спрайта
# персонажа — 64 px, поэтому 32 скрывает его почти целиком: это правильно для
# высокой травы в полный рост, но не для кустов.
#
# 12 px — та самая глубина, которую движок использует для обычного bush. То есть
# внешний вид СТОЯЩЕГО персонажа возвращается ровно к тому, что было до плагина,
# но теперь он не выпрыгивает из травы при ходьбе.
#
# Тег, не указанный здесь, сохраняет поведение движка по умолчанию — так что
# если позже появится настоящая :TallGrass (тег 10), она останется на 32 px.
#===============================================================================

module DeepGrass
  BUSH_DEPTHS = {
    :Grass => 12
  }
end

class Game_Character
  alias deep_grass_calculate_bush_depth calculate_bush_depth

  def calculate_bush_depth
    deep_grass_calculate_bush_depth
    return if @bush_depth.to_i == 0
    # Карта определяется так же, как в оригинале: персонаж может стоять на краю
    # и фактически находиться на соседней карте.
    this_map = (self.map.valid?(@x, @y)) ? [self.map, @x, @y]
                                         : $map_factory&.getNewMap(@x, @y, self.map.map_id)
    return if !this_map
    depth = DeepGrass::BUSH_DEPTHS[this_map[0].terrain_tag(this_map[1], this_map[2])&.id]
    @bush_depth = depth if depth
  end
end
